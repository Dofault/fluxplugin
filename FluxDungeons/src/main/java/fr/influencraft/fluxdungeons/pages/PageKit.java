package fr.influencraft.fluxdungeons.pages;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Arrays;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * What every full screen page of the plugin shares (Flux's {@code Screens}, see docs/technique/mcgui.md): one folder,
 * one stylesheet in the plain Minecraft look ({@code pages/style.css} of the jar), the pieces of a page (title bar,
 * bottom line) and the file helpers. Pages are generated: change the code or the lang file, never the files.
 */
public final class PageKit {

    /** Folder of the pages, under the page engine's own. */
    public static final String FOLDER = "fluxdungeons";
    /** Nothing is painted round the windows: the world shows there, darkened and blurred. */
    private static final String OVERLAY = "rgba(12, 12, 16, 0.45) blur";
    private static final Pattern FIRST_COLOR = Pattern.compile("&(#[0-9A-Fa-f]{6})");

    /** Where the pages take their texts and files (the plugin; a stub in tests). */
    public interface Source {
        /** A text of the lang file, variables replaced. */
        String raw(String key, String... vars);

        /** A file of the jar, null when missing. */
        InputStream resource(String path);

        void warn(String message);
    }

    private PageKit() {
    }

    /** The folder of the pages under the engine's, created, with the shared stylesheet. */
    public static Path prepare(Path root, Source source) throws IOException {
        Path dir = root.resolve(FOLDER);
        Files.createDirectories(dir.resolve("img"));
        copy(source, dir.resolve("style.css"), "pages/style.css");
        return dir;
    }

    /** A whole page; {@code sheets}: stylesheets after the shared one. */
    public static String html(String title, String bodyClass, String body, String... sheets) {
        StringBuilder links = new StringBuilder("<link rel=\"stylesheet\" href=\"style.css\">");
        for (String sheet : sheets) links.append("<link rel=\"stylesheet\" href=\"").append(sheet).append("\">");
        return "<!doctype html>\n<html lang=\"fr\"><head><meta charset=\"utf-8\"><title>" + esc(title) + "</title>"
                + "<meta name=\"ui:overlay\" content=\"" + OVERLAY + "\">"
                + "<!-- generated by FluxDungeons: edit the code or the lang file, not this file -->"
                + links + "</head>\n<body class=\"" + bodyClass + "\">" + body + "</body></html>\n";
    }

    /** The light bar on top of a page: its title (escaped by the caller), a tag, the player. */
    public static String titleBar(String title, String tag) {
        return "<header class=\"titlebar\"><h1>" + title + (tag.isEmpty() ? "" : "<em>" + tag + "</em>") + "</h1>"
                + "<div class=\"who\">{player}<img src=\"head:{player}\"></div></header>";
    }

    /** The first colour of a text of the server ({@code &#RRGGBB}), or the fallback. */
    public static String color(String text, String fallback) {
        Matcher m = text == null ? null : FIRST_COLOR.matcher(text);
        return m != null && m.find() ? m.group(1) : fallback;
    }

    /** A text without its colour codes. */
    public static String plain(String text) {
        return text == null ? "" : text.replaceAll("&#[0-9A-Fa-f]{6}|&[0-9a-fk-orA-FK-OR]|§[0-9a-fk-orA-FK-OR]", "");
    }

    /** A text without its colour codes, escaped for HTML. */
    public static String esc(String text) {
        return plain(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }

    /** A file of the jar copied as it is; false when the jar has none. */
    public static boolean copy(Source source, Path target, String resource) throws IOException {
        try (InputStream in = source.resource(resource)) {
            if (in == null) return false;
            write(target, in.readAllBytes());
            return true;
        }
    }

    public static void save(Path file, String content) throws IOException {
        write(file, content.getBytes(StandardCharsets.UTF_8));
    }

    /** Written only when the content changed (the page engine reloads what changed), never half written. */
    private static void write(Path file, byte[] bytes) throws IOException {
        if (Files.exists(file) && Arrays.equals(Files.readAllBytes(file), bytes)) return;
        Path tmp = file.resolveSibling(file.getFileName() + ".tmp");
        Files.write(tmp, bytes);
        Files.move(tmp, file, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
    }
}
