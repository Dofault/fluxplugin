"""Small caps digits for <smallcaps> (Flux Style.smallCaps), 2026-11-11.

Unicode has small caps letters (ᴀʙᴄ) but no small caps digits, so the digits and ( ) / inside <smallcaps> are drawn
here in QuinqueFive (5 px, the font of the vanilla theme) and given fixed private use characters U+F8D0 to U+F8DC in
the default font (ItemsAdder font_images with a symbol), so they work in any legacy text, no font component needed.
Their bottom sits on the baseline, like the small caps letters.

Output: ItemsAdder/contents/fluxtext/ of Labs (config.yml + textures). Then /iazip.
Keep SYMBOLS in sync with Style.SMALL_DIGITS (same order).
"""
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else "/home/influencraft/serveurs/04_labs/plugins/ItemsAdder/contents/fluxtext"

FONT = json.load(open(os.path.join(HERE, "..", "metiers", "quinquefive.json")))
EXTRA = {"/": ["..#", "..#", ".#.", "#..", "#.."], "(": [".#", "#.", "#.", "#.", ".#"], ")": ["#.", ".#", ".#", ".#", "#."]}
CHARS = "0123456789/()"
FIRST = 0xF8D0


def main():
    tex = os.path.join(OUT, "textures", "font", "smallcaps")
    os.makedirs(tex, exist_ok=True)
    lines = ["info:", "  namespace: fluxtext", "# generated by plugins/fluxplugin/Flux/assets/smallcaps/gen_smallcaps.py", "font_images:"]
    for i, c in enumerate(CHARS):
        rows = EXTRA.get(c) or FONT[c]
        im = Image.new("RGBA", (len(rows[0]), 5), (0, 0, 0, 0))
        for y, row in enumerate(rows):
            for x, p in enumerate(row):
                if p == "#":
                    im.putpixel((x, y), (255, 255, 255, 255))
        name = {"/": "slash", "(": "lparen", ")": "rparen"}.get(c, "d" + c)
        im.save(os.path.join(tex, name + ".png"))
        lines += [f"  sc_{name}:", f"    symbol: \"\\u{FIRST + i:04X}\"", f"    path: \"font/smallcaps/{name}.png\"",
                  "    scale_ratio: 5", "    y_position: 5", "    show_in_gui: false", "    suggest_in_command: false"]
    open(os.path.join(OUT, "config.yml"), "w").write("\n".join(lines) + "\n")
    print("wrote", len(CHARS), "glyphs to", OUT)


if __name__ == "__main__":
    main()
