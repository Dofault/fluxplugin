#!/usr/bin/env python3
"""Icon of the cosmetics (a wardrobe, chosen 2026-11-20): ItemsAdder item fluxcosmetics:penderie, used by the
Cosmetics button of the main menu and the cosmetics menu. Pure Python (no Pillow).

Usage: gen_icone.py <plugins dir of the server>   then /iazip
"""
import os
import struct
import sys
import zlib

PAL = {"k": "#15111B", "b": "#72513F", "B": "#A17A59", "G": "#FFD94D"}
PENDERIE = [
    "................",
    "..kkkkkkkkkkkk..",
    "..kBBBBBBBBBBk..",
    "..kbbbbkkbbbbk..",
    "..kbBBbkkbBBbk..",
    "..kbBBbkkbBBbk..",
    "..kbBBbkkbBBbk..",
    "..kbbbGkkGbbbk..",
    "..kbBBbkkbBBbk..",
    "..kbBBbkkbBBbk..",
    "..kbBBbkkbBBbk..",
    "..kbbbbkkbbbbk..",
    "..kBBBBBBBBBBk..",
    "..kkkkkkkkkkkk..",
    "...kk......kk...",
    "................",
]


def png(rows):
    def px(ch):
        h = PAL.get(ch)
        return bytes((0, 0, 0, 0)) if h is None else bytes(int(h[i:i + 2], 16) for i in (1, 3, 5)) + b"\xff"
    raw = b"".join(b"\x00" + b"".join(px(c) for c in row) for row in rows)
    chunk = lambda t, c: struct.pack(">I", len(c)) + t + c + struct.pack(">I", zlib.crc32(t + c) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 16, len(rows), 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def main(plugins):
    dest = os.path.join(plugins, "ItemsAdder", "contents", "fluxcosmetics")
    os.makedirs(os.path.join(dest, "textures", "item"), exist_ok=True)
    with open(os.path.join(dest, "textures", "item", "penderie.png"), "wb") as f:
        f.write(png(PENDERIE))
    with open(os.path.join(dest, "config.yml"), "w", encoding="utf-8") as f:
        f.write("# Generated by plugins/fluxplugin/FluxCosmetics/assets/gen_icone.py: do not edit by hand.\n"
                "info:\n  namespace: fluxcosmetics\n\nitems:\n  penderie:\n    display_name: ' '\n    resource:\n"
                "      material: PAPER\n      generate: true\n      textures:\n      - item/penderie.png\n")
    print("fluxcosmetics:penderie ->", dest)


if __name__ == "__main__":
    main(sys.argv[1])
