#!/usr/bin/env python3
"""FluxCrate: backgrounds of the crate menus (2026-10-29), pack « fluxcrate » of ItemsAdder.

  menu_caisse_apercu     close (0), title « CAISSE », icon (8); the rewards in 3 rows of 7 (19-25, 28-34, 37-43)
                         with the page arrows on each side (27, 35, dark cases of the arrows); the crate's button
                         on a gold case (49)
The frame starts half a slot below the window's top.
  menu_caisse_ouverture  close (0), title « OUVERTURE »; the strip (19-25), the middle case (22) in a gold frame
                         with an arrow above and below

    <venv with Pillow>/python3 gen_fonds.py <plugins dir of the server> [preview dir]
then /iazip.
"""
import os
import sys

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
FLUX = os.path.join(HERE, "..", "..", "Flux", "assets")
sys.path.insert(0, FLUX)
from fond_lib import case_sombre, generique_raccourci, objet, poser, tampon_case, title  # noqa: E402

W, H = 176, 221
GOLD, GOLD_DARK, GOLD_LIGHT = (240, 168, 0, 255), (138, 90, 20, 255), (255, 217, 77, 255)
DARK = (29, 23, 38, 255)


TOP = 9  # the frame starts half a slot down (2026-10-29)


def base(name, bottom):
    im = generique_raccourci(os.path.join(FLUX, "menu_generique.png"), TOP, bottom)
    title(im, name, objet(0)[1])
    case = tampon_case()
    for s in (0, 8):
        poser(im, case, *objet(s))
    return im, case


def gold(d, slot, pad=3):
    x, y = objet(slot)
    d.rounded_rectangle((x - pad, y - pad, x + 15 + pad, y + 15 + pad), radius=4, fill=GOLD_DARK)
    d.rounded_rectangle((x - pad + 1, y - pad + 1, x + 14 + pad, y + 14 + pad), radius=3, fill=GOLD)
    d.rounded_rectangle((x - 1, y - 1, x + 16, y + 16), radius=2, fill=GOLD_LIGHT)
    d.rounded_rectangle((x, y, x + 15, y + 15), radius=2, fill=DARK)


def apercu():
    im, case = base("Caisse", 18 + 18 * 5 + 19)
    d = ImageDraw.Draw(im)
    x0, y0 = objet(19)
    x1, y1 = objet(43)
    d.rounded_rectangle((x0 - 4, y0 - 4, x1 + 19, y1 + 19), radius=4, fill=DARK, outline=(13, 10, 18, 255))
    for row in (19, 28, 37):
        for s in range(row, row + 7):
            poser(im, case, *objet(s))
    for s in (27, 35):
        case_sombre(im, *objet(s))
    gold(d, 49)
    return im


def ouverture():
    im, case = base("Ouverture", 18 + 18 * 4 + 10)
    d = ImageDraw.Draw(im)
    x0, y0 = objet(19)
    x1, _ = objet(25)
    d.rounded_rectangle((x0 - 5, y0 - 5, x1 + 20, y0 + 20), radius=4, fill=DARK, outline=(13, 10, 18, 255))
    for s in range(19, 26):
        if s != 22:
            poser(im, case, *objet(s))
    gold(d, 22, pad=4)
    cx, y = objet(22)[0] + 8, objet(22)[1]
    d.polygon([(cx - 4, y - 11), (cx + 4, y - 11), (cx, y - 6)], fill=GOLD_LIGHT, outline=GOLD_DARK)
    d.polygon([(cx - 4, y + 26), (cx + 4, y + 26), (cx, y + 21)], fill=GOLD_LIGHT, outline=GOLD_DARK)
    return im


def main(plugins, preview=None):
    dest = os.path.join(plugins, "ItemsAdder", "contents", "fluxcrate")
    os.makedirs(os.path.join(dest, "textures", "gui"), exist_ok=True)
    lines = ["# Generated by plugins/fluxplugin/FluxCrate/assets/gen_fonds.py: do not edit by hand.",
             "info:", "  namespace: fluxcrate", "", "font_images:"]
    for gid, im in (("menu_caisse_apercu", apercu()), ("menu_caisse_ouverture", ouverture())):
        im.save(os.path.join(dest, "textures", "gui", gid + ".png"))
        lines += ["  %s:" % gid, "    show_in_gui: false", "    suggest_in_command: false",
                  '    path: "gui/%s.png"' % gid, "    scale_ratio: %d" % H, "    y_position: 13"]
        if preview:
            v = Image.new("RGBA", im.size, (60, 60, 60, 255))
            v.alpha_composite(im)
            v.resize((W * 3, H * 3), Image.NEAREST).save(os.path.join(preview, gid + "_x3.png"))
    open(os.path.join(dest, "config.yml"), "w").write("\n".join(lines) + "\n")
    print("pack fluxcrate ->", dest)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
