#!/usr/bin/env python3
"""FluxTags: the ItemsAdder pack « fluxtags » (2026-10-28) and the background of the /tags menu.

Tags (glyph ids, used by FluxTags), styles decided 2026-10-28:
  rang_<rank>          one per rank (FluxOffering ranks.yml): the existing grade tags of influtags, unchanged
  metier_<job>_<1..6>  one per EcoJobs job and tier (every 50 levels: Commun ... Fabuleux), style « gemme »
  beta, createur       special tags (permission), style « plein »
Each tag image exists twice in the pack:
  <id>                 chat size (9 px high), for %fluxtags_tag% in the chat and TAB
  <id>_r<1..5>         twice as big, placed on row 1..5 of the /tags menu (drawn in the title next to its button)

    <venv with Pillow>/python3 gen_tags.py <plugins dir of the server> [job style: gemme (chosen 2026-10-28) | plein | bordure]
Writes plugins/ItemsAdder/contents/fluxtags (textures, config.yml) and plugins/FluxTags/glyphs.yml (image widths),
then run /iazip.
"""
import os
import sys

import yaml
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tag_styles import RARITIES, STYLES  # noqa: E402
from fond_lib import generique_raccourci, title  # noqa: E402

RANK_COLOURS = ["c0c0c0", "9ad29a", "6ac7c7", "5ca8e6", "4e72e6", "8a5ce6", "d15ce6", "e65c9f", "ffd94d",
                "e6a85c", "e65c5c", "ff0033"]
SPECIALS = [("beta", "Bêta", "b376e5"), ("createur", "Créateur", "2bc4e8")]
ROWS = 5           # list rows of the menu, rows 1 to 5 of the chest
TAG_X = 43         # window x of the tag images (column 2)
GENERIC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Flux", "assets", "menu_generique.png")


def item_y(row):
    return 18 + 18 * row


def jobs(plugins):
    folder = os.path.join(plugins, "EcoJobs", "jobs")
    out = []
    for f in sorted(os.listdir(folder)):
        if f.endswith(".yml") and not f.startswith("_"):
            name = yaml.safe_load(open(os.path.join(folder, f))).get("name", f[:-4])
            out.append((f[:-4], strip(name)))
    return out


def ranks(plugins):
    data = yaml.safe_load(open(os.path.join(plugins, "FluxOffering", "ranks.yml")))
    data = data.get("ranks", data)
    return [(k, v["name"]) for k, v in data.items() if isinstance(v, dict) and "name" in v]


def strip(text):
    import re
    return re.sub(r"&#[0-9A-Fa-f]{6}|&[0-9a-fk-or]", "", text)


def background():
    """Generic background, title « TAGS », 5 dark strips (rows 1 to 5, columns 1 to 7): one tag per strip."""
    im = generique_raccourci(GENERIC, 0, 126)
    title(im, "Tags", item_y(0))
    d = ImageDraw.Draw(im)
    for row in range(1, ROWS + 1):
        y = item_y(row)
        d.rounded_rectangle((8 + 18 - 2, y - 2, 8 + 18 * 7 + 17, y + 17), radius=3, fill=(27, 21, 39, 255), outline=(13, 10, 18, 255))
        d.rounded_rectangle((8 + 18 - 1, y - 1, 8 + 18 * 7 + 16, y + 16), radius=2, outline=(72, 57, 96, 255))
    return im


def main(plugins, style):
    dest = os.path.join(plugins, "ItemsAdder", "contents", "fluxtags")
    tex = os.path.join(dest, "textures", "tags")
    os.makedirs(tex, exist_ok=True)
    draw = STYLES[style]
    tags = []
    grades = os.path.join(plugins, "ItemsAdder", "contents", "influtags", "textures", "grades")
    for i, (rid, name) in enumerate(ranks(plugins)):
        own = os.path.join(grades, rid + ".png")
        tags.append(("rang_" + rid, Image.open(own).convert("RGBA") if os.path.exists(own)
                     else STYLES["plein"](name, RANK_COLOURS[min(i, len(RANK_COLOURS) - 1)], 2)))
    for jid, name in jobs(plugins):
        for tier, (_, colour) in enumerate(RARITIES):
            tags.append(("metier_%s_%d" % (jid, tier + 1), draw(name, colour, tier)))
    for sid, name, colour in SPECIALS:
        tags.append((sid, STYLES["plein"](name, colour, 2)))
    lines = ["# Generated by plugins/fluxplugin/FluxTags/assets/gen_tags.py (style %s): do not edit by hand." % style,
             "info:", "  namespace: fluxtags", "", "font_images:"]
    for gid, im in tags:
        im.save(os.path.join(tex, gid + ".png"))
        lines += ["  %s:" % gid, "    show_in_gui: false", "    suggest_in_command: false",
                  '    path: "tags/%s.png"' % gid, "    scale_ratio: 9", "    y_position: 7"]
        for row in range(1, ROWS + 1):
            top = item_y(row)
            lines += ["  %s_r%d:" % (gid, row), "    show_in_gui: false", "    suggest_in_command: false",
                      '    path: "tags/%s.png"' % gid, "    scale_ratio: 18", "    y_position: %d" % (13 - top)]
    os.makedirs(os.path.join(dest, "textures", "gui"), exist_ok=True)
    background().save(os.path.join(dest, "textures", "gui", "menu_tags.png"))
    lines += ["  menu_tags:", "    show_in_gui: false", "    suggest_in_command: false",
              '    path: "gui/menu_tags.png"', "    scale_ratio: 221", "    y_position: 13"]
    open(os.path.join(dest, "config.yml"), "w").write("\n".join(lines) + "\n")
    # size of every tag image file: FluxTags places the menu images with it
    data = os.path.join(plugins, "FluxTags")
    os.makedirs(data, exist_ok=True)
    open(os.path.join(data, "glyphs.yml"), "w").write(
        "# Generated by FluxTags/assets/gen_tags.py: size in px of each tag image file [width, height].\n"
        + "".join("%s: [%d, %d]\n" % (gid, im.width, im.height) for gid, im in tags))
    print(len(tags), "tags (%s) ->" % style, dest)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "gemme")
