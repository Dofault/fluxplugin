#!/usr/bin/env python3
"""FluxAFK: the ItemsAdder pack « fluxafk », the bar shown under the « You are AFK » title (2026-10-31).

One image per step of the bar, bar_0 (empty) to bar_<STEPS> (full), shown one after the other by FluxAFK
(config bar.glyph "fluxafk:bar_{step}", bar.steps = STEPS): a dark violet capsule with a black outline, filled from
the left with a violet gradient (#5B2D9E to #B376E5), a pink light line on top (#E060A0) and a gold star at the head
of the filling (#FFD94D), the server's colours.

    <venv with Pillow>/python3 gen_bar.py <plugins dir of the server> [preview.png]
Writes plugins/ItemsAdder/contents/fluxafk (textures, config.yml), then run /iazip. Change STEPS here and bar.steps in
FluxAFK's config together.
"""
import os
import sys

from PIL import Image

STEPS = 20
W, H = 82, 9                   # image size, px (the subtitle shows it twice as big)
INNER = (2, 2, W - 3, H - 3)   # filled area, inclusive
SCALE = 9                      # ItemsAdder scale_ratio (= height)
Y = 7                          # ItemsAdder y_position, tuned in game

BLACK = (13, 13, 13, 255)
BACK = (30, 10, 60, 255)
DARK = (91, 45, 158, 255)
LIGHT = (179, 118, 229, 255)
PINK = (224, 96, 160, 255)
GOLD = (255, 217, 77, 255)
WHITE = (255, 247, 214, 255)


def mix(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(4))


def capsule(im):
    """Outline and background, corners rounded by one pixel."""
    px = im.load()
    for x in range(W):
        for y in range(H):
            corner = (x in (0, W - 1)) and (y in (0, H - 1))
            if corner:
                continue
            edge = x in (0, W - 1) or y in (0, H - 1) or ((x in (1, W - 2)) and (y in (1, H - 2)))
            px[x, y] = BLACK if edge else BACK


def frame(step):
    im = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    capsule(im)
    px = im.load()
    x0, y0, x1, y1 = INNER
    width = x1 - x0 + 1
    filled = round(width * step / STEPS)
    for i in range(filled):
        x = x0 + i
        colour = mix(DARK, LIGHT, i / max(1, width - 1))
        for y in range(y0, y1 + 1):
            px[x, y] = colour
        px[x, y0] = mix(colour, PINK, 0.6)          # light line on top
        px[x, y1] = mix(colour, BLACK, 0.35)        # shade at the bottom
    if filled > 0:
        # gold star at the head of the filling (a plus with a white heart), clipped to the inner area
        hx, hy = x0 + filled - 1, (y0 + y1) // 2
        for dx, dy in ((0, 0), (-1, 0), (1, 0), (0, -1), (0, 1)):
            x, y = hx + dx, hy + dy
            if x0 <= x <= x1 and y0 <= y <= y1:
                px[x, y] = GOLD
        px[hx, hy] = WHITE
    return im


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    plugins = sys.argv[1]
    dest = os.path.join(plugins, "ItemsAdder", "contents", "fluxafk")
    tex = os.path.join(dest, "textures", "bar")
    os.makedirs(tex, exist_ok=True)
    lines = ["# Generated by plugins/fluxplugin/FluxAFK/assets/gen_bar.py: do not edit by hand.",
             "info:", "  namespace: fluxafk", "", "font_images:"]
    frames = []
    for step in range(STEPS + 1):
        im = frame(step)
        im.save(os.path.join(tex, "bar_%d.png" % step))
        frames.append(im)
        lines += ["  bar_%d:" % step, "    show_in_gui: false", "    suggest_in_command: false",
                  '    path: "bar/bar_%d.png"' % step, "    scale_ratio: %d" % SCALE, "    y_position: %d" % Y]
    open(os.path.join(dest, "config.yml"), "w").write("\n".join(lines) + "\n")
    if len(sys.argv) > 2:
        # preview: every 5th step, 6 times bigger, on the dark background of the game's titles
        shown = frames[::5]
        sheet = Image.new("RGBA", (W + 4, (H + 3) * len(shown) + 3), (40, 40, 40, 255))
        for i, im in enumerate(shown):
            sheet.alpha_composite(im, (2, 3 + i * (H + 3)))
        sheet.resize((sheet.width * 6, sheet.height * 6), Image.NEAREST).save(sys.argv[2])
    print("fluxafk: %d images in %s, run /iazip" % (STEPS + 1, dest))


if __name__ == "__main__":
    main()
