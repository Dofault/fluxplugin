package fr.influencraft.fluxcasino.games;

import fr.influencraft.flux.api.MenuView;
import fr.influencraft.flux.api.TitleOverlay;
import org.bukkit.Bukkit;
import org.bukkit.Sound;
import org.bukkit.SoundCategory;
import org.bukkit.entity.Player;
import org.bukkit.plugin.Plugin;
import org.bukkit.scheduler.BukkitTask;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ThreadLocalRandom;

/**
 * Plinko ({@code [plinko]}): a ball dropped at the top of a pyramid of pegs bounces down to a prize bucket. The
 * result comes from a real physics simulation (gravity, damped bounces, walls) computed at once on click, then
 * replayed frame by frame in the window title (one frame per tick): the ball and the pegs it hits are ItemsAdder
 * glyphs placed to the pixel (pack influplinko, generated by assets/plinko/gen_plinko.py with the same geometry).
 * One sound per peg hit, a landing sound depending on the gain.
 *
 * <pre>
 *   %fluxplinko_last%   multiplier of the player's last ball ("x1.5 (15 jetons)", "aucun" before the first)
 *   %fluxplinko_count%  balls dropped since the server started
 *   %fluxplinko_erreur% reason of the last refused drop (not enough chips), empty otherwise
 * </pre>
 * Tuning kept after 2,000 simulated drops (2026-10-17): bell close to a binomial law (centre 20 %, edges 0.05 %),
 * about 3 s of fall, expected multiplier 0.94.
 */
final class Plinko extends CasinoGame {

    // Geometry (same as gen_plinko.py), in px of the window.
    private static final int ROWS = 10, SX = 14, SY = 13, Y0 = 48, CX = 88;
    private static final double START_Y = 38, BUCKET_TOP = 172, REST = 176;
    private static final int BUCKET_L = 13;
    static final String[] MULTIPLIERS = {"10", "3", "1.5", "1.1", "0.6", "0.4", "0.6", "1.1", "1.5", "3", "10"};

    // Physics (per tick; one frame = 1.5 tick, i.e. 12 sub-steps of 1/8).
    private static final double RB = 2.0, RP = 1.5, G = 0.6, E = 0.3, VMAX = 6, KICK = 0.2, DAMP = 0.5;
    private static final int SUBSTEPS = 8, SUBSTEPS_PER_FRAME = 12, MAX_FRAMES = 400;
    private static final int LIT_FRAMES = 3, BALL_Y_MIN = 30, BALL_Y_MAX = 181, MAX_BALLS = 12, HOLD = 12;

    private record Peg(double x, double y, int row) {
    }

    /** One frame: ball position, pegs hit during that frame. */
    private record Frame(int x, int y, List<Integer> hits) {
    }

    private static final List<Peg> PEGS = new ArrayList<>();

    static {
        for (int k = 0; k < ROWS; k++) {
            for (int i = 0; i < k + 3; i++) {
                PEGS.add(new Peg(CX + (i - (k + 2) / 2.0) * SX, Y0 + SY * k, k));
            }
        }
    }

    Plinko(Plugin plugin) {
        super(plugin, "plinko");
    }

    /** Balls in play for one player: one board per open menu, one frame per tick while something moves. */
    private static final class Board {
        final Player player;
        final MenuView view;
        final String base;
        final int cursor;
        final List<Ball> balls = new ArrayList<>();
        final int[] litUntil = new int[PEGS.size()];
        BukkitTask task;
        int tick;

        Board(Player player, MenuView view) {
            this.player = player;
            this.view = view;
            this.base = view.title();
            this.cursor = view.titleCursor();
        }
    }

    /** A ball: its fall simulated beforehand, the current frame, the tick it landed (-1 while falling). */
    private static final class Ball {
        final List<Frame> frames;
        final int bucket;
        final long bet;
        int index;
        int landedAt = -1;

        Ball(List<Frame> frames, int bucket, long bet) {
            this.frames = frames;
            this.bucket = bucket;
            this.bet = bet;
        }
    }

    private final Map<UUID, Board> boards = new ConcurrentHashMap<>();

    /**
     * Drops a ball. Several balls can fall at once (at most MAX_BALLS): every click adds one with its own fall. A
     * landed ball stays in its bucket for HOLD frames while others fall, then disappears; once nothing falls any
     * more, the last ones stay displayed.
     */
    @Override
    void act(Player player, MenuView view, String argument) {
        if (view == null || !view.isOpen()) return;
        Board board = boards.get(player.getUniqueId());
        if (board == null || !board.view.equals(view)) {
            if (board != null) stop(board); // previous board: balls still falling are settled
            board = new Board(player, view);
            boards.put(player.getUniqueId(), board);
        }
        if (board.balls.stream().noneMatch(b -> b.landedAt < 0)) board.balls.clear(); // new volley
        if (board.balls.size() >= MAX_BALLS) return;
        long bet = takeBet(player, view);
        if (bet < 0) return;
        List<Frame> frames = new ArrayList<>();
        int bucket = simulate(ThreadLocalRandom.current(), frames);
        board.balls.add(new Ball(frames, bucket, bet));
        if (bet > 0) view.refreshButtons(); // balance
        if (board.task == null) {
            Board b = board;
            board.task = Bukkit.getScheduler().runTaskTimer(plugin, () -> step(b), 0L, 1L);
        }
    }

    /** One frame of the board: moves every ball, sounds, then the full title. */
    private void step(Board board) {
        Player player = board.player;
        if (!board.view.isOpen() || !player.isOnline()) {
            stop(board);
            return;
        }
        int t = ++board.tick;
        boolean landed = false;
        for (Ball ball : board.balls) {
            if (ball.landedAt >= 0) continue;
            Frame frame = ball.frames.get(ball.index);
            List<Integer> previous = ball.index > 0 ? ball.frames.get(ball.index - 1).hits() : List.of();
            for (int p : frame.hits()) {
                board.litUntil[p] = t + LIT_FRAMES;
                // one sound per hit: not while the ball keeps resting on the same peg (contact on every frame)
                if (previous.contains(p)) continue;
                float pitch = 0.9f + PEGS.get(p).row() * 0.08f;
                player.playSound(player.getLocation(), Sound.BLOCK_AMETHYST_BLOCK_HIT, SoundCategory.MASTER, 0.6f, pitch);
            }
            if (ball.index == ball.frames.size() - 1) {
                ball.landedAt = t;
                land(player, ball);
                landed = true;
            } else {
                ball.index++;
            }
        }
        boolean falling = board.balls.stream().anyMatch(b -> b.landedAt < 0);
        if (falling) board.balls.removeIf(b -> b.landedAt >= 0 && t - b.landedAt > HOLD);

        TitleOverlay o = new TitleOverlay(board.base, board.cursor);
        boolean lit = false;
        for (int p = 0; p < PEGS.size(); p++) {
            if (board.litUntil[p] > t) {
                Peg peg = PEGS.get(p);
                o.add("plinko_clou_y" + ((int) peg.y() - 1), (int) peg.x() - 1, 3);
                lit = true;
            }
        }
        for (Ball ball : board.balls) {
            if (ball.landedAt >= 0) o.add("plinko_case", CX + (ball.bucket - 5) * SX - BUCKET_L / 2, BUCKET_L);
        }
        for (Ball ball : board.balls) {
            Frame frame = ball.frames.get(ball.index);
            o.add("plinko_bille_y" + Math.max(BALL_Y_MIN, Math.min(BALL_Y_MAX, frame.y() - 2)), frame.x() - 2, 5);
        }
        board.view.showTitle(o.toString());
        if (landed) board.view.refreshButtons(); // last result, number of balls
        if (!falling && !lit) {
            board.task.cancel();
            board.task = null;
        }
    }

    private void stop(Board board) {
        // Menu closed or player gone during the fall: every falling ball already has its result (simulated
        // beforehand) and its bet taken, its gain is paid right away, without animation.
        for (Ball ball : board.balls) {
            if (ball.landedAt < 0) {
                ball.landedAt = board.tick;
                settle(board.player, ball);
            }
        }
        if (board.task != null) board.task.cancel();
        board.task = null;
        boards.remove(board.player.getUniqueId(), board);
    }

    @Override
    void shutdown() {
        new ArrayList<>(boards.values()).forEach(this::stop);
    }

    private void settle(Player player, Ball ball) {
        String multiplier = MULTIPLIERS[ball.bucket];
        pay(player, ball.bet, Double.parseDouble(multiplier), "x" + multiplier,
                "x" + multiplier + (ball.bet > 0 ? " (%gain% jetons)" : ""));
    }

    /** A ball lands: gain, sound depending on the gain. */
    private void land(Player player, Ball ball) {
        settle(player, ball);
        double m = Double.parseDouble(MULTIPLIERS[ball.bucket]);
        if (m >= 3) {
            player.playSound(player.getLocation(), Sound.UI_TOAST_CHALLENGE_COMPLETE, SoundCategory.MASTER, 0.7f, 1.2f);
        } else if (m >= 1) {
            player.playSound(player.getLocation(), Sound.ENTITY_PLAYER_LEVELUP, SoundCategory.MASTER, 0.6f, 1.4f);
        } else {
            player.playSound(player.getLocation(), Sound.BLOCK_NOTE_BLOCK_BASS, SoundCategory.MASTER, 0.7f, 0.8f);
        }
    }

    // ------------------------------------------------------------------ physics

    /** Simulates one fall, fills frames (one per frame) and returns the bucket index (0 to 10). */
    private static int simulate(ThreadLocalRandom rng, List<Frame> frames) {
        double x = CX + rng.nextDouble(-1.5, 1.5), y = START_Y, vx = 0, vy = 0;
        double dt = 1.0 / SUBSTEPS;
        for (int f = 0; f < MAX_FRAMES; f++) {
            List<Integer> hits = new ArrayList<>();
            for (int s = 0; s < SUBSTEPS_PER_FRAME; s++) {
                vy += G * dt;
                x += vx * dt;
                y += vy * dt;
                for (int p = 0; p < PEGS.size(); p++) {
                    Peg peg = PEGS.get(p);
                    double dx = x - peg.x(), dy = y - peg.y();
                    double d = Math.hypot(dx, dy);
                    if (d >= RB + RP || d < 1e-6) continue;
                    double nx = dx / d, ny = dy / d;
                    x = peg.x() + nx * (RB + RP);
                    y = peg.y() + ny * (RB + RP);
                    double vn = vx * nx + vy * ny;
                    if (vn < 0) {
                        vx -= (1 + E) * vn * nx;
                        vy -= (1 + E) * vn * ny;
                        vx *= DAMP;
                        // a little tangential randomness, stronger when the ball falls right on top of the peg
                        double kick = rng.nextDouble(-KICK, KICK) + (Math.abs(nx) < 0.25 ? (rng.nextBoolean() ? 0.25 : -0.25) : 0);
                        vx += -ny * kick;
                        vy += nx * kick;
                        if (!hits.contains(p)) hits.add(p);
                    }
                }
                if (y < BUCKET_TOP) {
                    double n = 3 + Math.max(0, Math.min(ROWS - 1, (y - Y0) / SY));
                    double half = (n - 1) / 2 * SX + 7 - RB;
                    if (x < CX - half) {
                        x = CX - half;
                        vx = Math.abs(vx) * E;
                    }
                    if (x > CX + half) {
                        x = CX + half;
                        vx = -Math.abs(vx) * E;
                    }
                }
                // balanced on a peg: a push makes it fall to one side
                if (!hits.isEmpty() && Math.abs(vx) < 0.15 && Math.abs(vy) < 0.3) {
                    vx += rng.nextBoolean() ? 0.6 : -0.6;
                }
                double speed = Math.hypot(vx, vy);
                if (speed > VMAX) {
                    vx = vx / speed * VMAX;
                    vy = vy / speed * VMAX;
                }
            }
            if (y >= BUCKET_TOP) {
                int bucket = (int) Math.max(0, Math.min(10, Math.round((x - (CX - 5 * SX)) / SX)));
                int cx = CX + (bucket - 5) * SX;
                frames.add(new Frame((int) Math.round(x), (int) Math.round(y), hits));
                while (y < REST) {
                    y = Math.min(REST, y + Math.max(1.5, vy));
                    x += (cx - x) * 0.4;
                    frames.add(new Frame((int) Math.round(x), (int) Math.round(y), List.of()));
                }
                frames.add(new Frame(cx, (int) REST, List.of()));
                return bucket;
            }
            frames.add(new Frame((int) Math.round(x), (int) Math.round(y), hits));
        }
        // should not happen (stuck ball): closest bucket
        int bucket = (int) Math.max(0, Math.min(10, Math.round((x - (CX - 5 * SX)) / SX)));
        frames.add(new Frame(CX + (bucket - 5) * SX, (int) REST, List.of()));
        return bucket;
    }
}
