#!/usr/bin/env python3
"""Writes the tools of FluxTools (tools/<id>.yml) from tools_source.yml and the scales below.

    python3 plugins/fluxplugin/FluxTools/assets/gen_tools.py [--plugins <plugins folder>]

Then /tools reload. Levelled tools (Virale, Phenomene): 20 levels, the tool XP comes from use (1 XP = 1 second of
farming the resource, see xp-metiers in FluxTools' config; forced-points of the source come first). Other tools: fixed
enchantments, unrepairable.
"""
import argparse
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_PLUGINS = "/home/influencraft/serveurs/04_labs/plugins"

LEVELS = 20
EXPONENT = 1.6  # first levels in minutes, last ones in hours
HOURS_TO_MAX = {"virale": 30, "phenomene": 40}
# tool level -> enchantment level: every enchantment of a levelled tool starts at 0
MAIN_STEPS = {1: 1, 3: 2, 6: 3, 9: 4, 12: 5, 16: 6, 20: 7}  # Sharpness, Power, Density
EFFICIENCY_STEPS = {1: 1, 3: 2, 6: 3, 9: 4, 12: 5}          # Efficiency stops at V, Haste takes over
HASTE_STEPS = {16: 1, 18: 2, 20: 3}                         # Celerite (EcoEnchants), 3 at most
SECONDARY_STEPS = {4: 1, 10: 2, 17: 3}                      # Fortune, Looting
UNBREAKING_STEPS = {2: 1, 8: 2, 14: 3}
ABILITY_LEVELS = [5, 11]                                    # level of the 1st ability, then of the 2nd (mace)

MAIN_ENCHANT = {"pioche": "efficiency", "pelle": "efficiency", "hache": "efficiency", "houe": "efficiency",
                "epee": "sharpness", "arc": "power", "masse": "density"}
FIXED = {
    "pioche": {"efficiency": 5, "fortune": 3}, "pelle": {"efficiency": 5, "fortune": 3},
    "hache": {"efficiency": 5, "fortune": 3}, "houe": {"efficiency": 5, "fortune": 3},
    "epee": {"sharpness": 5, "looting": 3}, "arc": {"power": 5, "flame": 1},
}
LEVELLED = {
    "pioche": ["fortune", "unbreaking"], "pelle": ["fortune", "unbreaking"],
    "hache": ["fortune", "unbreaking"], "houe": ["fortune", "unbreaking"],
    "epee": ["looting", "unbreaking"], "masse": ["unbreaking"],
}
# Signature ability (EcoEnchants) of a tool.
ABILITIES = {
    "pioche_virale": {"filon": 1}, "pioche_phenomene": {"tranchee": 1},
    "pelle_virale": {"tranchee": 1}, "hache_virale": {"tranchee": 1}, "hache_phenomene": {"buche": 3},
    "houe_virale": {"recolte": 9}, "epee_virale": {"immolation": 4}, "epee_phenomene": {"frappe_du_ravageur": 3},
    "masse_phenomene": {"colere_de_thor": 3, "seisme": 2},
}
HEADER = "# Generated by plugins/fluxplugin/FluxTools/assets/gen_tools.py: do not edit by hand. Then /tools reload.\n"


def thresholds(tier):
    weights = [n ** EXPONENT for n in range(1, LEVELS + 1)]
    unit = HOURS_TO_MAX[tier] * 3600 / sum(weights)
    out, total = [], 0
    for w in weights:
        total += unit * w
        out.append(int(round(total)))
    return out


def tool(tool_id, source, forced):
    family, tier = source["family"], source["tier"]
    levelled = tier in HOURS_TO_MAX
    out = {k: source[k] for k in ("name", "description", "tier", "family", "material") if k in source}
    if "model" in source:
        out["model"] = source["model"]
    out["durability"] = source["durability"]
    out["repairable"] = levelled
    if levelled:
        if MAIN_ENCHANT[family] == "efficiency":
            enchants = {"efficiency": dict(EFFICIENCY_STEPS), "celerite": dict(HASTE_STEPS)}
        else:
            enchants = {MAIN_ENCHANT[family]: dict(MAIN_STEPS)}
        for e in LEVELLED[family]:
            enchants[e] = dict(UNBREAKING_STEPS if e == "unbreaking" else SECONDARY_STEPS)
        for i, (e, v) in enumerate(ABILITIES.get(tool_id, {}).items()):
            enchants[e] = {ABILITY_LEVELS[min(i, len(ABILITY_LEVELS) - 1)]: v}
        out["enchantments"] = enchants
        out["level"] = {"thresholds": thresholds(tier)}
        out["points"] = forced.get(family, {})
    else:
        out["enchantments"] = dict(FIXED[family])
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--plugins", default=DEFAULT_PLUGINS)
    args = parser.parse_args()
    source = yaml.safe_load(open(os.path.join(HERE, "tools_source.yml"), encoding="utf-8"))
    folder = os.path.join(args.plugins, "FluxTools", "tools")
    os.makedirs(folder, exist_ok=True)
    for tool_id, s in source["tools"].items():
        text = HEADER + yaml.safe_dump(tool(tool_id, s, source["forced-points"]), allow_unicode=True, sort_keys=False, width=200)
        open(os.path.join(folder, tool_id + ".yml"), "w", encoding="utf-8").write(text)
    print(len(source["tools"]), "tools written in", folder)


if __name__ == "__main__":
    main()
