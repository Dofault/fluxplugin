FACES = ("north", "south", "west", "east", "up", "down")


class Cube:
    """style on front and back, sides on the other four (the same unless given); plane = the only face of a dark plane."""

    def __init__(self, low, high, style, rotation=(0, 0, 0), origin=None, sides=None, plane=None):
        self.low, self.high = list(low), list(high)
        self.style = style
        self.sides = sides or style
        self.rotation = list(rotation)
        self.origin = list(origin) if origin else [(low[i] + high[i]) / 2 for i in range(3)]
        self.plane = plane

    def size(self, face):
        dx, dy, dz = (self.high[i] - self.low[i] for i in range(3))
        return {"north": (dx, dy), "south": (dx, dy), "west": (dz, dy), "east": (dz, dy), "up": (dx, dz), "down": (dx, dz)}[face]

    def faces(self):
        """{face: (texture index, atlas rectangle)} in texels; 0 shaded, 1 emissive (the pale plates of the chevrons)."""
        out = {}
        for face in FACES:
            if self.plane and face != self.plane:
                continue
            w, h = self.size(face)
            style = self.style if face in ("north", "south") else self.sides
            index = 1 if style == "glow" else 0
            out[face] = (index, (ATLAS_MAIN, ATLAS_GLOW)[index].rect(style, max(1, round(w * DENSITY)), max(1, round(h * DENSITY))))
        return out

    def rotated(self, p):
        """A point of the cube after its rotation (x, then y, then z, as in Blockbench and in rotation.x/y/z)."""
        ax, ay, az = (math.radians(v) for v in self.rotation)
        x, y, z = (p[i] - self.origin[i] for i in range(3))
        y, z = y * math.cos(ax) - z * math.sin(ax), y * math.sin(ax) + z * math.cos(ax)
        x, z = x * math.cos(ay) + z * math.sin(ay), -x * math.sin(ay) + z * math.cos(ay)
        x, y = x * math.cos(az) - y * math.sin(az), x * math.sin(az) + y * math.cos(az)
        return x + self.origin[0], y + self.origin[1], z + self.origin[2]


def box(low, high, style, sides=None):
    return Cube(low, high, style, sides=sides)


def plane(low, high, face):
    """A dark plane hiding the head."""
    return Cube(low, high, "void", plane=face)


def bar(a, b, width, z0, z1, style, lean=0.0, sides="side", pivot_z=None):
    """Plate from a to b as seen from the front (x, y), its length along local y, turning around its middle.

    lean tips its top: negative = backwards. Plates of a same stack share pivot_z so they lean as one piece.
    """
    (ax, ay), (bx, by) = a, b
    cx, cy = (ax + bx) / 2, (ay + by) / 2
    length = math.hypot(bx - ax, by - ay) / math.cos(math.radians(lean))
    angle = round(math.degrees(math.atan2(-(bx - ax), by - ay)), 6)
    if angle > 90:
        angle -= 180
    elif angle < -90:
        angle += 180
    low, high = [cx - width / 2, cy - length / 2, z0], [cx + width / 2, cy + length / 2, z1]
    pz = (z0 + z1) / 2 if pivot_z is None else pivot_z
    return Cube(low, high, style, (lean, 0, angle), [cx, cy, pz], sides)


def diamond(cx, cy, side, z0, z1, style, sides="side"):
    """Square on its point, seen from the front."""
    h = side / 2
    return Cube([cx - h, cy - h, z0], [cx + h, cy + h, z1], style, (0, 0, 45), [cx, cy, (z0 + z1) / 2], sides)


def mirror(c):
    other = {"west": "east", "east": "west"}.get(c.plane, c.plane)
    return Cube([-c.high[0], c.low[1], c.low[2]], [-c.low[0], c.high[1], c.high[2]], c.style,
                (c.rotation[0], -c.rotation[1], -c.rotation[2]), [-c.origin[0], c.origin[1], c.origin[2]], c.sides, other)


def both(*right):
    """Cubes built on the player's right, with their mirror on the left."""
    out = []
    for c in right:
        out += [c, mirror(c)]
    return out


def chevron(apex, tip, width, z0, z1, style, lean=0.0, pivot_z=None, shift=0.05):
    """Two mirrored bars; the second is a hair thicker so that their overlap at the apex cannot flicker."""
    a = bar(apex, tip, width, z0, z1, style, lean, pivot_z=pivot_z)
    b = bar(apex, (-tip[0], tip[1]), width, z0, z1, style, lean, pivot_z=pivot_z)
    b.low[2] -= shift
    b.high[2] += shift
    return [a, b]


