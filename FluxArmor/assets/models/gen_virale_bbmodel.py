def png64(image):
    buf = io.BytesIO()
    image.save(buf, "PNG")
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def bbmodel(model):
    elements, outliner = [], []
    for name, cubes in model.items():
        ids = []
        for c in cubes:
            ident = str(uuid.uuid4())
            ids.append(ident)
            faces = {f: {"uv": list(r), "texture": t} for f, (t, r) in c.faces().items()}
            elements.append({"name": c.style, "type": "cube", "uuid": ident, "from": [round(v, 3) for v in c.low],
                             "to": [round(v, 3) for v in c.high], "origin": [round(v, 3) for v in c.origin],
                             "rotation": [round(v, 3) for v in c.rotation], "faces": faces})
        outliner.append({"name": name, "uuid": str(uuid.uuid4()), "origin": [0, 0, 0], "children": ids})
    # A texture named *neon* is emissive for FluxArmor.
    textures = [{"name": n, "uuid": str(uuid.uuid4()), "width": ATLAS, "height": ATLAS, "uv_width": ATLAS,
                 "uv_height": ATLAS, "source": png64(a.image)} for n, a in (("virale_armure.png", ATLAS_MAIN), ("virale_neon.png", ATLAS_GLOW))]
    return {"meta": {"format_version": "4.10", "model_format": "free", "box_uv": False}, "name": "virale",
            "resolution": {"width": ATLAS, "height": ATLAS}, "elements": elements, "outliner": outliner, "textures": textures}


def item_elements(cubes, scale, centre_y):
    """Cubes as elements of an item model: units per skin pixel, centre_y at the middle, front towards -z."""
    swap = {"south": "north", "north": "south", "west": "east", "east": "west", "up": "up", "down": "down"}

    def mc(p):
        return [round(8 - p[0] * scale, 3), round(8 + (p[1] - centre_y) * scale, 3), round(8 - p[2] * scale, 3)]

    elements = []
    for c in cubes:
        lo, hi = mc(c.low), mc(c.high)
        low, high = [min(lo[i], hi[i]) for i in range(3)], [max(lo[i], hi[i]) for i in range(3)]
        for v in low + high:
            if v < -16 or v > 32:
                raise SystemExit("Cube outside the item model range: %s %s" % (low, high))
        faces = {}
        glow = False
        for f, (t, (u0, v0, u1, v1)) in c.faces().items():
            glow = glow or t == 1
            k = 16 / ATLAS
            uv = [u0 * k, v0 * k, u1 * k, v1 * k]
            if f in ("up", "down"):
                uv = [uv[2], uv[3], uv[0], uv[1]]
            faces[swap[f]] = {"uv": [round(v, 4) for v in uv], "texture": "#glow" if t else "#main"}
        e = {"from": low, "to": high, "faces": faces}
        if glow:
            e["light_emission"] = 15
        rx, ry, rz = c.rotation
        if rx or ry or rz:
            # The change of frame turns the model half a turn around y: x and z rotations change sign.
            e["rotation"] = {"origin": mc(c.origin), "x": round(-rx, 3), "y": round(ry, 3), "z": round(-rz, 3)}
        elements.append(e)
    return elements


