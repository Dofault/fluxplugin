def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) + (255,)


# Half way between diamond (hue 180) and the viral blue (hue 222), slightly on the diamond side.
PALE, LIGHT, MAIN_C, MID, DARK, DEEP, GLOOM = (rgb(h) for h in
                                               ("#8CF0FF", "#4CDCFF", "#1CBEF8", "#0E9EE8", "#0A74C8", "#0A4E96", "#072F62"))
VOID = rgb("#060E1E")
IRON = [rgb(h) for h in ("#364459", "#2B374A", "#1F2838")]


class Atlas:
    """Hands out a painted rectangle per (style, size): faces of the same size and style share their picture."""

    def __init__(self):
        self.image = Image.new("RGBA", (ATLAS, ATLAS), (0, 0, 0, 0))
        self.x = self.y = self.row = 0
        self.known = {}

    def rect(self, style, w, h):
        key = (style, w, h)
        if key not in self.known:
            if self.x + w > ATLAS:
                self.x, self.y = 0, self.y + self.row
                self.row = 0
            if self.y + h > ATLAS:
                raise SystemExit("Atlas is full: raise ATLAS.")
            noise = random.Random(sum(ord(c) for c in style) * 1000 + w * 31 + h)
            for y in range(h):
                for x in range(w):
                    self.image.putpixel((self.x + x, self.y + y), PAINT[style](x, y, w, h, noise))
            self.known[key] = (self.x, self.y, self.x + w, self.y + h)
            self.x += w
            self.row = max(self.row, h)
        return self.known[key]


def pick(noise, a, b, ratio=0.6):
    return a if noise.random() < ratio else b


def paint_band(x, y, w, h, n):
    """Pale band along the plate, the chevron bars of the reference."""
    pos, size = (x, w) if h >= w else (y, h)
    if size <= 2:
        return pick(n, LIGHT, PALE)
    t = abs(pos - (size - 1) / 2) / (size / 2)
    if t < 0.42:
        return pick(n, PALE, LIGHT, 0.92)
    if t < 0.8:
        return pick(n, LIGHT, MAIN_C, 0.8)
    return pick(n, MAIN_C, MID, 0.85)


def paint_frame(x, y, w, h, n):
    """Pale rim around a darker field, the tassets and pauldrons of the reference."""
    if min(w, h) < 3:
        return pick(n, LIGHT, PALE)
    if x == 0 or y == 0 or x == w - 1 or y == h - 1:
        return pick(n, LIGHT, PALE, 0.8)
    if min(w, h) >= 5 and (x == 1 or y == 1 or x == w - 2 or y == h - 2):
        return pick(n, MAIN_C, LIGHT, 0.8)
    return pick(n, MID, MAIN_C, 0.8)


def paint_check(x, y, w, h, n):
    """Hand-placed squares of three tones, the sleeves and blocks of the reference."""
    if y == h - 1 and h >= 3:
        return pick(n, MID, DARK)
    return pick(n, LIGHT, MAIN_C, 0.7) if (x // 2 + y // 2) % 2 == 0 else pick(n, MAIN_C, MID, 0.8)


def paint_side(x, y, w, h, n):
    """Thickness of a plate: darker than its face, so the plate reads as a block."""
    return MID if (x + y) % 3 else pick(n, MID, DARK, 0.6)


def paint_rib(x, y, w, h, n):
    """Horizontal stripes."""
    return pick(n, LIGHT, PALE, 0.8) if y % 2 == 0 else pick(n, MAIN_C, MID, 0.8)


def paint_ribdark(x, y, w, h, n):
    return pick(n, MID, MAIN_C, 0.8) if y % 2 == 0 else pick(n, DARK, DEEP, 0.7)


def paint_vee(x, y, w, h, n):
    """Pale chevron pointing down, painted on a block."""
    d = abs(x - (w - 1) / 2) * 0.9 - (h - 1 - y) * 0.9 + 1
    if abs(d) < 1.1:
        return pick(n, PALE, LIGHT, 0.85)
    return pick(n, MAIN_C, MID, 0.65) if d < 0 else pick(n, MID, DARK, 0.65)


def paint_mid(x, y, w, h, n):
    return pick(n, MID, DARK, 0.75)


def paint_deep(x, y, w, h, n):
    return pick(n, DEEP, GLOOM, 0.6)


def paint_void(x, y, w, h, n):
    return VOID


def paint_gauntlet(x, y, w, h, n):
    """Dark forearm, the notch at the wrist of the reference."""
    if w >= 4 and y >= h - 2 and abs(x - (w - 1) / 2) < 1:
        return VOID
    return IRON[(x // 2 + y // 2 + n.randint(0, 1)) % 3]


