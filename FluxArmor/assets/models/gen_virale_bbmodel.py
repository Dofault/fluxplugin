CUBE_CORNERS = {"north": (6, 2, 0, 4), "south": (3, 7, 5, 1), "west": (2, 3, 1, 0), "east": (7, 6, 4, 5), "up": (2, 6, 7, 3), "down": (1, 5, 4, 0)}
BACKGROUND = (20, 26, 38, 255)


def rot_x(d):
    a = math.radians(d)
    return np.array([[1, 0, 0], [0, math.cos(a), -math.sin(a)], [0, math.sin(a), math.cos(a)]])


def rot_y(d):
    a = math.radians(d)
    return np.array([[math.cos(a), 0, math.sin(a)], [0, 1, 0], [-math.sin(a), 0, math.cos(a)]])


def quads(cubes, limb=None):
    """Faces of cubes as (corners, uv, texture index); limb = (pivot, rotation matrix) to pose the body part."""
    out = []
    for c in cubes:
        pts = [np.array(c.rotated((c.high[0] if i & 4 else c.low[0], c.high[1] if i & 2 else c.low[1], c.high[2] if i & 1 else c.low[2])))
               for i in range(8)]
        for f, (t, r) in c.faces().items():
            q = np.array([pts[k] for k in CUBE_CORNERS[f]])
            if limb:
                q = (q - limb[0]) @ limb[1].T + limb[0]
            out.append((q, np.array([[r[0], r[1]], [r[2], r[1]], [r[2], r[3]], [r[0], r[3]]], float), t))
    return out


def body_box(low, high, colour, limb=None):
    """Part of the bare player, to see where the body shows through the armour."""
    pts = [np.array((high[0] if i & 4 else low[0], high[1] if i & 2 else low[1], high[2] if i & 1 else low[2]), float) for i in range(8)]
    out = []
    for f in FACES:
        q = np.array([pts[k] for k in CUBE_CORNERS[f]])
        if limb:
            q = (q - limb[0]) @ limb[1].T + limb[0]
        out.append((q, None, colour))
    return out


def render(faces, view, size, scale, centre=(0, 17), background=BACKGROUND, night=False):
    """Orthographic z-buffer rasteriser with Minecraft's two entity lights."""
    atlases = [np.array(ATLAS_MAIN.image, float), np.array(ATLAS_GLOW.image, float)]
    image = np.zeros((size, size, 4))
    image[:, :] = background
    depth = np.full((size, size), -1e9)
    l0, l1 = np.array([0.2, 1, -0.7]), np.array([-0.2, 1, 0.7])
    l0, l1 = l0 / np.linalg.norm(l0), l1 / np.linalg.norm(l1)
    for q, uv, colour in faces:
        p = q @ view.T
        n = np.cross(p[3] - p[0], p[1] - p[0])
        length = np.linalg.norm(n)
        if length < 1e-9 or n[2] / length <= 0:
            continue
        wn = np.cross(q[3] - q[0], q[1] - q[0])
        wn = wn / np.linalg.norm(wn)
        light = min(1.0, 0.4 + 0.6 * (max(0, wn @ l0) + max(0, wn @ l1)))
        sx = size / 2 + (p[:, 0] - centre[0]) * scale
        sy = size / 2 - (p[:, 1] - centre[1] * view[1, 1]) * scale
        for tri in ((0, 1, 2), (0, 2, 3)):
            ax, ay = sx[list(tri)], sy[list(tri)]
            x0, x1 = max(0, int(ax.min())), min(size - 1, int(ax.max()) + 1)
            y0, y1 = max(0, int(ay.min())), min(size - 1, int(ay.max()) + 1)
            if x1 < x0 or y1 < y0:
                continue
            xs, ys = np.meshgrid(np.arange(x0, x1 + 1) + 0.5, np.arange(y0, y1 + 1) + 0.5)
            d = (ay[1] - ay[2]) * (ax[0] - ax[2]) + (ax[2] - ax[1]) * (ay[0] - ay[2])
            if abs(d) < 1e-9:
                continue
            w0 = ((ay[1] - ay[2]) * (xs - ax[2]) + (ax[2] - ax[1]) * (ys - ay[2])) / d
            w1 = ((ay[2] - ay[0]) * (xs - ax[2]) + (ax[0] - ax[2]) * (ys - ay[2])) / d
            w2 = 1 - w0 - w1
            inside = (w0 >= 0) & (w1 >= 0) & (w2 >= 0)
            if not inside.any():
                continue
            z = w0 * p[tri[0], 2] + w1 * p[tri[1], 2] + w2 * p[tri[2], 2]
            for r, k in zip(*np.nonzero(inside)):
                px, py = k + x0, r + y0
                if z[r, k] <= depth[py, px]:
                    continue
                if uv is None:
                    c = np.array(colour, float)
                else:
                    u = w0[r, k] * uv[tri[0], 0] + w1[r, k] * uv[tri[1], 0] + w2[r, k] * uv[tri[2], 0]
                    v = w0[r, k] * uv[tri[0], 1] + w1[r, k] * uv[tri[1], 1] + w2[r, k] * uv[tri[2], 1]
                    c = atlases[colour][min(ATLAS - 1, int(v)), min(ATLAS - 1, int(u))]
                    if c[3] < 10:
                        continue
                f = 1.0 if uv is not None and colour == 1 else light * (0.18 if night else 1.0)
                image[py, px] = (c[0] * f, c[1] * f, c[2] * f, 255)
                depth[py, px] = z[r, k]
    return Image.fromarray(image.clip(0, 255).astype("uint8"), "RGBA")


def scene(model, swing=0.0, pitch=0.0, yaw=0.0):
    """All pieces on a player; swing = legs and arms rotation in degrees (walking), pitch / yaw of the head."""
    leg_r = (np.array([-1.9, 12.0, 0]), rot_x(swing))
    leg_l = (np.array([1.9, 12.0, 0]), rot_x(-swing))
    arm_r = (np.array([-5.0, 22.0, 0]), rot_x(-swing))
    arm_l = (np.array([5.0, 22.0, 0]), rot_x(swing))
    head = (np.array([0.0, 24.0, 0]), rot_y(yaw) @ rot_x(pitch))
    skin, shirt, trousers = (200, 149, 109, 255), (61, 122, 122, 255), (59, 79, 160, 255)
    faces = body_box([-4, 24, -4], [4, 32, 4], skin, head) + body_box([-4, 12, -2], [4, 24, 2], shirt)
    faces += body_box([-8, 12, -2], [-4, 24, 2], shirt, arm_r) + body_box([4, 12, -2], [8, 24, 2], shirt, arm_l)
    faces += body_box([-3.9, 0, -2], [0.1, 12, 2], trousers, leg_r) + body_box([-0.1, 0, -2], [3.9, 12, 2], trousers, leg_l)
    faces += quads(helmet(), head) + quads(model["plastron_torse"]) + quads(model["jambieres_torse"])
    arm, leg, boot = model["plastron_bras_droit"], model["jambieres_jambe_droite"], model["bottes_jambe_droite"]
    faces += quads(arm, arm_r) + quads([mirror(c) for c in arm], arm_l)
    faces += quads(leg + boot, leg_r) + quads([mirror(c) for c in leg + boot], leg_l)
    return faces


def previews(model, folder):
    os.makedirs(folder, exist_ok=True)
    faces = scene(model)
    views = [rot_y(0), rot_x(8) @ rot_y(-30), rot_y(-90), rot_x(8) @ rot_y(145), rot_y(180)]
    sheet = Image.new("RGBA", (340 * len(views), 640), BACKGROUND)
    for i, v in enumerate(views):
        sheet.paste(render(faces, v, 640, 14, centre=(0, 21)).crop((150, 0, 490, 640)), (340 * i, 0))
    sheet.save(os.path.join(folder, "virale_vues.png"))
    poses = [(scene(model, 30), rot_x(8) @ rot_y(-30), False), (scene(model, 50), rot_y(90), False),
             (scene(model, 0, 35, 50), rot_x(10) @ rot_y(-20), False), (faces, rot_x(10) @ rot_y(-30), True)]
    sheet = Image.new("RGBA", (340 * len(poses), 640), BACKGROUND)
    for i, (f, v, night) in enumerate(poses):
        im = render(f, v, 640, 14, centre=(0, 21), background=(6, 8, 16, 255) if night else BACKGROUND, night=night)
        sheet.paste(im.crop((150, 0, 490, 640)), (340 * i, 0))
    sheet.save(os.path.join(folder, "virale_poses.png"))
    arm, leg, boot = model["plastron_bras_droit"], model["jambieres_jambe_droite"], model["bottes_jambe_droite"]
    pieces = [(helmet(), (0, 33), 12), (model["plastron_torse"] + arm + [mirror(c) for c in arm], (0, 19), 12),
              (model["jambieres_torse"] + leg + [mirror(c) for c in leg], (0, 8), 15), (boot + [mirror(c) for c in boot], (0, 4), 20)]
    views = [rot_y(0), rot_x(15) @ rot_y(-25), rot_y(-90), rot_y(180)]
    sheet = Image.new("RGBA", (320 * len(views), 320 * len(pieces)), BACKGROUND)
    for r, (cubes, centre, scale) in enumerate(pieces):
        for i, v in enumerate(views):
            sheet.paste(render(quads(cubes), v, 320, scale, centre=centre), (320 * i, 320 * r))
    sheet.save(os.path.join(folder, "virale_pieces.png"))
    ATLAS_MAIN.image.save(os.path.join(folder, "atlas.png"))


