#!/usr/bin/env python3
"""Assembles the entity shaders of the FluxArmor pack: ItemsAdder's 26.1+ ones (assets/shaders/ia, emotes kept,
"legacy" armours removed: unused, and relying on values ItemsAdder fills in when it generates them) plus the FluxArmor
3D rendering (assets/shaders/armor*.vsh.glsl) and Flux's profile bust (assets/shaders/buste*.glsl, generated by
Flux/assets/buste/gen_buste.py). Output: src/main/resources/shaders/entity.{vsh,fsh}.

    python3 assets/assemble_shaders.py

Run again after any change of a .glsl file, or when ItemsAdder changes its shaders
(internal/shaders/armors_emotes/ia_overlay_26_1_plus/ in its jar: copy them into assets/shaders/ia).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
IA = os.path.join(HERE, "shaders/ia")
OUT = os.path.join(HERE, "../src/main/resources/shaders")

GUARD = """
// FluxArmor: armour in real 3D, see plugins/fluxplugin/FluxArmor and docs/technique/fluxarmor.md.
#if defined(PER_FACE_LIGHTING) && defined(NO_OVERLAY) && defined(ALPHA_CUTOUT) && !defined(EMISSIVE)
#define FA_ARMOR
#endif
"""
# Rank of the vertex (gl_BaseVertexARB) and corners shared by the 4 vertices of a face (subgroupQuadBroadcast).
# Version 410: the highest macOS compiles; without these extensions the shader keeps the flat fallback armour.
EXTENSIONS = """#version 410
#extension GL_KHR_shader_subgroup_basic : enable
#extension GL_KHR_shader_subgroup_quad : enable
#extension GL_ARB_shader_draw_parameters : enable
"""
VARYINGS = """
#ifdef FA_ARMOR
{q} float faValid;
#endif
"""


def rep(s, a, b):
    assert s.count(a) == 1, a
    return s.replace(a, b)


def read(nom):
    return open(os.path.join(HERE, nom)).read()


def main():
    os.makedirs(OUT, exist_ok=True)
    v = open(os.path.join(IA, "entity.vsh")).read()
    v = rep(v, "#version 330\n", EXTENSIONS)
    v = rep(v, "#moj_import <minecraft:sample_lightmap.glsl>\n", "#moj_import <minecraft:sample_lightmap.glsl>\n" + GUARD)
    v = rep(v, "out float vGameTime;\n", "out float vGameTime;\n" + VARYINGS.format(q="out"))
    v = rep(v, "void main() {\n", read("shaders/armor_functions.vsh.glsl") + "\nvoid main() {\n")
    v = rep(v, "    //%START_EMOTES%\n", read("shaders/armor.vsh.glsl") + "\n    //%START_EMOTES%\n")
    open(os.path.join(OUT, "entity.vsh"), "w").write(v)

    f = open(os.path.join(IA, "entity.fsh")).read()
    f = re.sub(r"//%START_CUSTOM_ARMORS_VARS%.*?//%END_CUSTOM_ARMORS_VARS%\n", "", f, flags=re.S)
    f = re.sub(r"    //%START_CUSTOM_ARMORS%.*?//%END_CUSTOM_ARMORS%\n", "", f, flags=re.S)
    f = rep(f, "#moj_import <minecraft:dynamictransforms.glsl>\n", "#moj_import <minecraft:dynamictransforms.glsl>\n" + GUARD
            + "#moj_import <minecraft:projection.glsl>\n")  # once, unconditional: moj_import ignores #ifdef
    f = rep(f, "in float vGameTime;\n", "in float vGameTime;\n" + VARYINGS.format(q="in"))
    # profile bust (Flux): player heads of the menus, needs the projection outside armour too
    f = rep(f, "out vec4 fragColor;\n", "out vec4 fragColor;\n\n"
            + read("shaders/buste_constantes.glsl") + read("shaders/buste.fsh.glsl") + "\n")
    f = rep(f, """    if (isTopLayer == 1 || origTexCoord0.y >= 0.25)
        UV = origTexCoord0;
""", """    if (isTopLayer == 1 || origTexCoord0.y >= 0.25)
        UV = origTexCoord0;
    vec2 busteTexture;
    bool busteMasque;
    float busteLumiere;
    if (busteUV(busteTexture, busteMasque, busteLumiere)) {
        if (busteMasque) discard;
        UV = busteTexture;
        faceVertexColor = vec4(vec3(busteLumiere), faceVertexColor.a);
    }
""")
    # 3D armour faces whose vertices the GPU did not group: dropped (see armor.vsh.glsl).
    f = rep(f, "void main() {\n", """void main() {
#ifdef FA_ARMOR
    if (faValid < 0.9999) discard;
#endif
""")
    assert not re.search(r"%[A-Z_]+%", re.sub(r"//.*", "", f)), "ItemsAdder variable not replaced"
    open(os.path.join(OUT, "entity.fsh"), "w").write(f)
    print("Shaders written to", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
